# Stage 6 — .container.urdf twins of stage 5's output
# =============================================================================
#
# Codifies what was, during this prototype's actual debugging session, a
# manual `sed` pass: rewrite every mesh <filename> whose prefix is
# HOST_REPO_ROOT to CONTAINER_REPO_ROOT instead, so the result is loadable
# from inside the hpp-agimus-arm64 container.
#
# HOST_REPO_ROOT is a fixed literal, NOT derived from HERE (tried that
# first — wrong): merge-arm's mesh <filename> paths are inherited
# verbatim from assets/ur10/ur10_robot_generated.urdf and
# assets/robotiq_2f85/urdf/robotiq_2f85_generated.urdf, neither of which
# this pipeline generates — the first is a pre-existing vendored xacro
# export (same category as generated/ground.urdf, no live generator at
# all), the second's *source xacro* has the host path hand-patched
# directly into it (stage 2's docstring), not resolved dynamically. Both
# carry HOST_REPO_ROOT regardless of where merge-arm itself is run from
# — confirmed live: running merge-arm from inside the container still
# produced host-absolute mesh paths, because HERE-based substitution
# only affects paths *this script* constructs itself (stages 3/4's own
# mesh references), not ones copied in from these two upstream files.

def write_container_variant() -> None:
    for name in ("ur10_robotiq.urdf", "ur10_robotiq_right.urdf"):
        src = GEN_DIR / name
        dst = GEN_DIR / name.replace(".urdf", ".container.urdf")
        text = src.read_text()
        text = re.sub(re.escape(HOST_REPO_ROOT), CONTAINER_REPO_ROOT, text)
        dst.write_text(text)
        n_paths = text.count(CONTAINER_REPO_ROOT)
        print(f"wrote {dst.relative_to(HERE.parent.parent)} "
              f"({n_paths} container-absolute mesh path(s))")


