#!/usr/bin/env python3
"""Build every generated asset for the IKEA LACK table prototype.

Local prototype only — see README.md (this whole directory only exists on
the local/ikea-furniture-prototype branch). Consolidates what used to be
five separate scripts (rescale_robotiq_meshes.py, generate_robotiq_urdf.sh,
generate_hole_peg_meshes.py, generate_urdf_srdf.py, merge_ur10_robotiq.py —
removed) into one, since they form a single linear pipeline with no
independent reuse: each stage's output is the next stage's only input, and
none of them were ever run standalone against a different scene. A sixth,
rescale_ikea_meshes.py, was dropped entirely rather than merged — its
output (assets/meshes_scaled/{table,leg1..4}.stl, the real vendored IKEA
mesh rescaled) was never consumed by anything: generate_urdf_srdf's visual
geometry moved to generate_hole_peg_meshes' fresh box-with-holes/peg
meshes instead (see that stage's own docstring below for why), leaving
the rescaled real-product meshes orphaned.

PIPELINE ORDER (default: every stage, in order; --only for just one)
--------------------------------------------------------------------
  1. rescale-robotiq-meshes
     Robotiq DAE/STL -> assets/robotiq_2f85/meshes_scaled/
  2. robotiq-urdf
     xacro -> assets/robotiq_2f85/urdf/robotiq_2f85_generated.urdf
  3. hole-peg-meshes
     trimesh boolean ops
     -> assets/meshes_generated/{table_with_holes,leg_with_peg}.stl
  4. urdf-srdf
     table.{urdf,srdf}, leg{1..4}.{urdf,srdf} -> generated/
  5. merge-arm
     UR10 + Robotiq + pedestal -> generated/ur10_robotiq{,_right}.urdf
  6. container-variant
     host-path -> container-path twins of stage 5's output (see below)

Stages 1-2 only need re-running if the vendored Robotiq xacro/mesh sources
change. Stages 3-4 are what actually get edited/re-run during scene
iteration (mesh dimensions, socket positions, handle geometry). Stage 5
only needs re-running if the arm/gripper mount or pedestal changes.

ground.urdf / workbench.urdf in generated/ have no corresponding stage
here — they're plain hand-authored static geometry (no meshes, pure
primitive boxes), never generated by any script, committed as-is.

CONTAINER VS. HOST PATHS — read before running stage 5 or 6
--------------------------------------------------------------
pyhpp only imports inside the hpp-agimus-arm64 container (see
debug_view_frames.py's docstring), which mounts this repo at
/home/thanhndv212/devel/hpp/src/long_tamp — NOT at this host's own path
(/Users/thanhndv212/Develop/agimus-ws/long-tamp). Every mesh <filename> and
every top-level URDF/SRDF path baked in by this script is HERE-relative
(``Path(__file__).parent``), so whichever environment you *run this
script from* determines which paths end up in generated/ — there is no
detection or translation of that automatically.

Stages 3-4's output (table/leg URDFs) currently sits with container-correct
paths because that's where this script was last run from — if you edit and
re-run stage 4 from the host, its output reverts to host paths and won't
resolve when a task script tries to load it inside the container. Simplest
fix: re-run from inside the container (matches how every fix during this
prototype's actual debugging session was applied — see docker exec
examples in this repo's own session history / task_assemble_table.py).

Stage 5's output (the two arm URDFs) additionally gets an explicit
``.container.urdf`` *twin* (stage 6, --containerize) — a older, pre-
existing naming convention this script preserves rather than invents:
config/ikea_table_config.yaml's paths.robot entries reference
ur10_robotiq(.container)?.urdf specifically. Table/leg/ground/workbench
URDFs have no such twin-naming convention; they're just regenerated
in-place per environment.
"""

